import { act, fireEvent, render, screen } from '@testing-library/react-native';
import i18n from '../src/i18n';
import ExchangeScreen from '../src/modules/exchange/ExchangeScreen';
import { convert, convertHundi, ExchangeFailure, getRate, type Conversion, type HundiConversion, type Quote } from '../src/modules/exchange/api';
jest.mock('../src/components/useRouteHeadingFocus', () => ({ useRouteHeadingFocus: () => ({ current: null }) }));
jest.mock('expo-router', () => ({ usePathname: () => '/exchange', router: { navigate: jest.fn() } }));
jest.mock('@react-native-async-storage/async-storage', () => require('@react-native-async-storage/async-storage/jest/async-storage-mock'));
jest.mock('../src/modules/exchange/api', () => ({ ...jest.requireActual('../src/modules/exchange/api'), convert: jest.fn(), convertHundi: jest.fn(), getRate: jest.fn() }));
const quote: Quote = { quoteId: 'synthetic-cbm', provider: 'cbm', sourceName: 'Central Bank of Myanmar', sourceUrl: 'https://forex.cbm.gov.mm/index.php/fxrate', rateType: 'MARKET_TRADING', sourceTimeZone: 'Asia/Yangon', publicationDate: '2026-11-13', publishedAt: null, publicationPrecision: 'DATE', retrievedAt: '2026-11-14T12:00:00Z', expiresAt: '2099-01-01T00:00:00Z', freshness: 'PREVIOUS_PUBLISHED_RATE', quotedKrw: '100', mmkPer100Krw: '273.88', referenceMmkPer100Krw: '157.14', referenceMmkPerKrw: '1.5714', referenceSourceUrl: 'https://forex.cbm.gov.mm/api/latest', krwPerQuotedUnit: '100', mmkUnit: '273.88', mmkPerKrw: '2.7388', krwPerMmk: '0.365123411713', rateDisplayDecimalPlaces: 14 };
const result: Conversion = { from: 'KRW', to: 'MMK', amount: '1000000', convertedAmount: '2738800.00', belowDisplayPrecision: false, quote, calculationVersion: 'krw-mmk-cbm-market-1', calculationPrecision: 80, rounding: 'FLOOR_ONCE', decimalPlaces: 2 };
const hundi: HundiConversion = { from: 'KRW', to: 'MMK', amount: '100000', convertedAmount: '325925.92', belowDisplayPrecision: false, rates: { mmkPerUsd: '4400', usdPerKrw: '1350', mmkPerKrw: '3.259259259259' }, calculationVersion: 'krw-mmk-hundi-1', calculationPrecision: 80, rounding: 'FLOOR_ONCE', decimalPlaces: 2 };
async function flush() { await act(async () => {}); }
async function tick(ms = 400) { await act(async () => { jest.advanceTimersByTime(ms); }); }
async function ready() { await render(<ExchangeScreen />); await flush(); }
beforeEach(async () => {
  jest.useFakeTimers();
  jest.resetAllMocks();
  await i18n.changeLanguage('en');
  jest.mocked(getRate).mockResolvedValue(quote);
  jest.mocked(convert).mockResolvedValue(result);
  jest.mocked(convertHundi).mockResolvedValue(hundi);
});
afterEach(() => { jest.useRealTimers(); });
it('shows official source metadata and converts instantly in both directions', async () => {
  await ready();
  expect(getRate).toHaveBeenCalledWith(false);
  expect(screen.queryByLabelText('Convert')).toBeNull();
  expect(screen.getByText('Central Bank of Myanmar ↗')).toBeTruthy();
  expect(screen.queryByText('Preview')).toBeNull();
  expect(screen.getByText('100 KRW = 273.88 MMK')).toBeTruthy();
  expect(screen.getByText('1 KRW = 2.7388 MMK')).toBeTruthy();
  expect(screen.getByText(i18n.t('exchange.referenceComparison', { rate: '1.5714' }))).toBeTruthy();
  expect(screen.getByText('Published: 2026-11-13 · MMT')).toBeTruthy();
  expect(screen.getByText(/^Last updated: .* MMT$/)).toBeTruthy();
  await fireEvent.changeText(screen.getByLabelText('Amount (KRW)'), '1000000');
  await tick();
  expect(convert).toHaveBeenCalledWith('KRW', 'MMK', '1000000');
  expect(screen.getByText('2738800.00 MMK')).toBeTruthy();
  expect(screen.getByText(i18n.t('exchange.result'))).toBeTruthy();
  await fireEvent.press(screen.getByLabelText('Swap currencies'));
  expect(screen.getByLabelText('Amount (MMK)').props.value).toBe('1000000');
  jest.mocked(convert).mockResolvedValueOnce({ ...result, from: 'MMK', to: 'KRW', amount: '1000000', convertedAmount: '365123', decimalPlaces: 0 });
  await tick();
  expect(convert).toHaveBeenLastCalledWith('MMK', 'KRW', '1000000');
  expect(screen.getByText('365123 KRW')).toBeTruthy();
});
it('keeps official conversion unavailable and retains the amount until the rate refreshes', async () => {
  jest.mocked(getRate).mockRejectedValueOnce(new ExchangeFailure('RATE_UNAVAILABLE'));
  await ready();
  expect(screen.getByText(i18n.t('exchange.officialUnavailableHint'))).toBeTruthy();
  expect(screen.getByText(i18n.t('exchange.errors.RATE_UNAVAILABLE'))).toBeTruthy();
  await fireEvent.changeText(screen.getByLabelText('Amount (KRW)'), '123.45');
  await tick();
  expect(convert).not.toHaveBeenCalled();
  expect(screen.getByLabelText('Amount (KRW)').props.value).toBe('123.45');
  await fireEvent.press(screen.getByLabelText('Refresh rate'));
  await flush();
  expect(getRate).toHaveBeenLastCalledWith(true);
  await tick();
  expect(convert).toHaveBeenCalledWith('KRW', 'MMK', '123.45');
  expect(screen.getByText('2738800.00 MMK')).toBeTruthy();
});
it('converts with user hundi rates in both directions, validates rates, and resets USD/KRW', async () => {
  await ready();
  await fireEvent.press(screen.getByLabelText('Hundi rate'));
  expect(screen.queryByText(i18n.t('exchange.officialTitle'))).toBeNull();
  expect(screen.getByText(i18n.t('exchange.hundiTitle'))).toBeTruthy();
  expect(screen.getByLabelText('USD per KRW').props.value).toBe('1350');
  await fireEvent.changeText(screen.getByLabelText('MMK per USD (hundi rate)'), '4400');
  await fireEvent.changeText(screen.getByLabelText('Amount (KRW)'), '100000');
  await tick();
  expect(convertHundi).toHaveBeenCalledWith('KRW', 'MMK', '100000', '4400', '1350');
  expect(screen.getByText('325925.92 MMK')).toBeTruthy();
  expect(screen.getByText(i18n.t('exchange.resultHundi'))).toBeTruthy();
  expect(screen.getByText(i18n.t('exchange.mmkPerKrwApplied', { rate: '3.259259259259' }))).toBeTruthy();
  jest.mocked(convertHundi).mockResolvedValueOnce({ ...hundi, from: 'MMK', to: 'KRW', amount: '100000', convertedAmount: '1350000', decimalPlaces: 0 });
  await fireEvent.press(screen.getByLabelText('From MMK To KRW'));
  await tick();
  expect(convertHundi).toHaveBeenLastCalledWith('MMK', 'KRW', '100000', '4400', '1350');
  expect(screen.getByText('1350000 KRW')).toBeTruthy();
  await fireEvent.changeText(screen.getByLabelText('MMK per USD (hundi rate)'), '0');
  expect(screen.getByText(i18n.t('exchange.errors.INVALID_HUNDI_RATE'))).toBeTruthy();
  expect(screen.queryByTestId('exchange-result')).toBeNull();
  const calls = jest.mocked(convertHundi).mock.calls.length;
  await tick();
  expect(convertHundi).toHaveBeenCalledTimes(calls);
  await fireEvent.changeText(screen.getByLabelText('USD per KRW'), '1.23456');
  expect(screen.getByText(i18n.t('exchange.errors.INVALID_USD_KRW_RATE'))).toBeTruthy();
  await fireEvent.changeText(screen.getByLabelText('USD per KRW'), '1400');
  await fireEvent.press(screen.getByLabelText('Reset to 1350'));
  expect(screen.getByLabelText('USD per KRW').props.value).toBe('1350');
});
it('ignores late conversions after the amount changes and preserves failed inputs', async () => {
  let finish!: (value: Conversion) => void;
  const pending = new Promise<Conversion>(resolve => { finish = resolve; });
  jest.mocked(convert).mockReturnValueOnce(pending);
  await ready();
  await fireEvent.changeText(screen.getByLabelText('Amount (KRW)'), '1000000');
  await tick();
  expect(convert).toHaveBeenCalledTimes(1);
  await fireEvent.changeText(screen.getByLabelText('Amount (KRW)'), '2.01');
  await act(async () => { finish(result); });
  expect(screen.queryByTestId('exchange-result')).toBeNull();
  jest.mocked(convert).mockRejectedValueOnce(new ExchangeFailure('NETWORK'));
  await tick();
  expect(screen.getByText(i18n.t('exchange.errors.NETWORK'))).toBeTruthy();
  expect(screen.getByLabelText('Amount (KRW)').props.value).toBe('2.01');
});
it('shows Burmese validation and the API below-precision result without local arithmetic', async () => {
  await i18n.changeLanguage('my');
  await ready();
  const amountLabel = `${i18n.t('exchange.amount')} (KRW)`;
  await fireEvent.changeText(screen.getByLabelText(amountLabel), '1,000');
  expect(screen.getByText(i18n.t('exchange.errors.INVALID_AMOUNT'))).toBeTruthy();
  await tick();
  expect(convert).not.toHaveBeenCalled();
  jest.mocked(convert).mockResolvedValueOnce({ ...result, to: 'KRW', amount: '0.01', convertedAmount: '0', belowDisplayPrecision: true, decimalPlaces: 0 });
  await fireEvent.changeText(screen.getByLabelText(amountLabel), '0.01');
  await tick();
  expect(screen.getByText(i18n.t('exchange.belowPrecision'))).toBeTruthy();
  expect(screen.getByText('0 KRW')).toBeTruthy();
});

it('keeps Hundi available when CBM is unavailable', async () => {
  jest.mocked(getRate).mockRejectedValueOnce(new ExchangeFailure('RATE_UNAVAILABLE'));
  await ready();
  await fireEvent.press(screen.getByLabelText('Hundi rate'));
  await fireEvent.changeText(screen.getByLabelText('MMK per USD (hundi rate)'), '4400');
  await fireEvent.changeText(screen.getByLabelText('Amount (KRW)'), '100000');
  await tick();
  expect(convertHundi).toHaveBeenCalledWith('KRW','MMK','100000','4400','1350');
  expect(screen.getByText('325925.92 MMK')).toBeTruthy();
});
